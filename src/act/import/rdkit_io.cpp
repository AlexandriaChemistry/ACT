/*! \brief Update variables in the Fragment data structure based on inchi.
 * If the inchi is not found in the database, only the inchi itself will be added
 * to the Fragment, not formula, iupac etc.
 * \param[in]    msg_handler For debugging and info
 * \param[in]    amols Database of molecule information read from alexandria.json of ACT-utilities
 * \param[in]    inchi InChi symbol generated by external library
 * \param[inout] fptr  Pointer to Fragment data structure
 * \return true if information was found, false otherwise
 */
static bool updateFragmentFromInchi(MsgHandler           *msg_handler,
                                    const AlexandriaMols &amols,
                                    const std::string    &inchi,
                                    Fragment             *fptr)
{
    auto amol  = amols.findInChi(inchi);
    if (nullptr != amol)
    {
        fptr->setInchi(inchi);
        fptr->setIupac(amol->iupac);
        fptr->setCharge(amol->charge);
        fptr->setMass(amol->mass);
        fptr->setFormula(amol->formula);
        // The database value may be wrong for some compounds. The thermochemistry
        // computes the symmetry number from the structure and only uses this as
        // a fallback.
        if (amol->symmetryNumber > 0)
        {
            fptr->setSymmetryNumber(amol->symmetryNumber);
        }
        return true;
    }
    else
    {
        msg_handler->msg(ACTStatus::Warning,
                         gmx::formatString("Could not find '%s' in database", inchi.c_str()));
        fptr->setInchi(inchi);
        return false;
    }
}

/*! \brief Fill a fragment from an RDKit molecule, for fragments not in the database
 * The mass, formal charge and formula are computed by RDKit, the symmetry
 * number and multiplicity are set to 1.
 * \param[in]  mol       RDKit structure of the fragment
 * \param[in]  inchi     The InChi of the fragment
 * \param[out] fptr      The fragment to fill
 * \param[in]  fragIndex Indices of the atoms of the fragment in the whole molecule
 */
static void updateFragmentsFromRDKit(const RDKit::RWMol     &mol,
                                     const std::string      &inchi,
                                     Fragment               *fptr,
                                     const std::vector<int> &fragIndex)
{
    fptr->setInchi(inchi);
    fptr->setMass(RDKit::Descriptors::calcExactMW(mol));
    fptr->setCharge(RDKit::MolOps::getFormalCharge(mol));
    fptr->setFormula(RDKit::Descriptors::calcMolFormula(mol));
    //! \todo get this stuff from RDKit as well
    fptr->setSymmetryNumber(1);
    fptr->setMultiplicity(1);
    fptr->setAtoms(fragIndex);
}

/*! \brief Generate an InChi and add it to a fragment
 * Use RDKit to generate InChis for molecule fragments (typically molecules)
 * and store it in the fragptr.
 *
 * 
 * \param[in]    msg_handler For warnings and errors
 * \param[in]    amols       Database read from alexandria.json
 * \param[in]    mol         RDKit molecule structure
 * \param[inout] fragptr     ACT fragment descriptors
 */
static void addInchiToFragments(MsgHandler            *msg_handler,
                                const AlexandriaMols  &amols,
                                RDKit::RWMol          *mol,
                                std::vector<Fragment> *fragptr)
{
    RDKit::ExtraInchiReturnValues rv;
    if (fragptr->size() == 1)
    {
        const auto inchi = MolToInchi(*mol, rv);
        if (!updateFragmentFromInchi(msg_handler, amols, inchi, &((*fragptr)[0])))
        {
            std::vector<int> fragIndex;
            for(size_t i = 0; i < mol->getNumAtoms(); i++)
            {
                fragIndex.push_back(i);
            }
            updateFragmentsFromRDKit(*mol, inchi, &((*fragptr)[0]), fragIndex);
        }
    }
    else
    {
        // Use RDKit to get fragments back as molecules
        bool sanitizeFrags = true;
        std::vector<int> fragindex(mol->getNumAtoms());
        const auto frags = RDKit::MolOps::getMolFrags(*mol, sanitizeFrags,
                                                      &fragindex);
        if (frags.size() != fragptr->size())
        {
            msg_handler->msg(ACTStatus::Error,
                             gmx::formatString("Number of fragments found by ACT (%zu) does not match RDKit (%zu)",
                                               fragptr->size(), frags.size()));
        }
        else
        {
            int myfrag = 0;
            for(const auto &frag : frags)
            {
                const auto inchi = MolToInchi(*frag, rv);
                if (!updateFragmentFromInchi(msg_handler, amols, inchi, &((*fragptr)[myfrag])))
                {
                    std::vector<int> fragIndex;
                    for(int f = 0; f < static_cast<int>(fragindex.size()); f++)
                    {
                        if (fragindex[f] == myfrag)
                        {
                            fragIndex.push_back(f);
                        }
                    }
                    updateFragmentsFromRDKit(*frag, inchi, &((*fragptr)[myfrag]), fragIndex);
                }
                myfrag += 1;
            }
        }
    }
}

/*! \brief Compute bond order
 * \param[in] msg_handler For warnings and errors
 * \param[in] bt          RDKit bond information
 * \return ACT compatible bond order (double)
 */
static double bondTypeValue(MsgHandler            *msg_handler,
                            RDKit::Bond::BondType  bt)
{
    double order = 0;
    switch (bt)
    {
    case RDKit::Bond::BondType::SINGLE:
        order = 1;
        break;
    case RDKit::Bond::BondType::DOUBLE:
        order = 2;
        break;
    case RDKit::Bond::BondType::TRIPLE:
        order = 3;
        break;
    case RDKit::Bond::BondType::AROMATIC:
        order = 1.5;
        break;
    default:
        msg_handler->msg(ACTStatus::Error, "Unknown bondtype");
    }
    return order;
}

/*! \brief Check whether special block is supported by force field
 */
static bool abeSupported(MsgHandler              *msg_handler,
                         const ForceField        *pd,
                         const AtomBondtypeEntry &abe,
                         bool                    oneH)
{
    // Check whether atom types occur in FF
    std::vector<const ParticleType *> ptypes;
    for(const auto &atp : abe.atomtypes)
    {
        const Identifier id(atp.name);
        if (!pd->hasParticleType(id))
        {
            if (atp.atomnumber <= 0)
            {
                msg_handler->msg(ACTStatus::Warning,
                                 gmx::formatString("No atomnumber defined for atomtype %s in special case '%s'",
                                                   atp.name.c_str(), abe.name.c_str()));
            }
            bool isH = (atp.atomnumber == 1);

            if (oneH && isH && pd->hasParticleType("h"))
            {
                ptypes.push_back(pd->findParticleType("h"));
                continue;
            }
            msg_handler->msg(ACTStatus::Warning,
                             gmx::formatString("Atom type %s not found in force field", atp.name.c_str()));
            return false;
        }
        // Save particle type ptrs for bonds
        ptypes.push_back(pd->findParticleType(id));
    }
    // Now check bonds
    auto itype = InteractionType::BONDS;
    if (!pd->interactionPresent(itype))
    {
        msg_handler->msg(ACTStatus::Error, "No bonds in force field");
        return false;
    }
    const auto& fs = pd->findForcesConst(itype);
    const std::string bstr("bondtype");
    for(const auto &sb : abe.bonds)
    {
        if (ptypes[sb.ai]->hasOption(bstr) &&
            ptypes[sb.aj]->hasOption(bstr))
        {
            const Identifier bondId({ ptypes[sb.ai]->optionValue(bstr),
                          ptypes[sb.aj]->optionValue(bstr) },
                                    { sb.order },
                                    CanSwap::Yes);
            if (!fs.parameterExists(bondId))
            {
                msg_handler->msg(ACTStatus::Warning,
                                 gmx::formatString("Bond %s not found in force field", bondId.id().c_str()));
                return false;
            }
        }
    }
    return true;
}

/*! \brief Lookup and insert special atom types and bond orders.
 * \param[in]    msg_handler For error and warning messages
 * \param[in]    pd          A force field to check compatibility of special atoms and bonds
 * \param[in]    abe         Database of special atom and bond types
 * \param[in]    mol2        An RDKit molecule
 * \param[inout] exper       The Experiment structure that may be modified
 * \param[inout] bonds       The bonds that may be modified
 * \param[in]    oneH        If true, hydrogens will not be modified, whatever the database says
 */
static void lookUpSpecial(MsgHandler                           *msg_handler,
                          const ForceField                     *pd,
                          const std::vector<AtomBondtypeEntry> &abe,
                          RDKit::RWMol                         *mol2,
                          Experiment                           *exper,
                          std::vector<Bond>                    *bonds,
                          bool                                  oneH)
{
    // Boolean vectors to check if atom in molecule already assigned, necessary since
    // switch in atom_bond.xml from special to general
    std::vector<bool> atomAssigned(exper->NAtom(), false);
    std::vector<bool> bondAssigned(bonds->size(), false);
    // Check whether we have any of those special cases.
    for(size_t i = 0; i < abe.size(); i++)
    {
        // Make RDKit matcher for our pattern
        const RDKit::SmartsMatcher matcher(abe[i].name, abe[i].smarts);
        // Check whether the pattern is valid, to prevent RDKit from throwing an exception
        if (!matcher.isValid())
        {
            msg_handler->msg(ACTStatus::Warning,
                             gmx::formatString("Smarts pattern '%s' invalid.",
                                               abe[i].smarts.c_str()));
        }
        else if (matcher.hasMatch(*mol2))
        {
            msg_handler->msg(ACTStatus::Verbose,
                             gmx::formatString("Found match for %s '%s'.",
                                               abe[i].name.c_str(), abe[i].smarts.c_str()));
            auto qmol = RDKit::v1::SmartsToMol(abe[i].smarts, 0, false);
            if (msg_handler)
            {
                msg_handler->msg(ACTStatus::Verbose,
                                 gmx::formatString("qmol has %d atoms",
                                                   qmol->getNumAtoms())); 
            }
            if (abeSupported(msg_handler, pd, abe[i], oneH))
            {
                const int NOTSET = -666;
                // All matches, RDKit returns at most 1000 by default, which
                // is not enough for a box with many compounds
                RDKit::SubstructMatchParameters params;
                params.maxMatches = std::numeric_limits<unsigned int>::max();
                const std::vector<RDKit::MatchVectType> matchVect = RDKit::SubstructMatch(*mol2, *qmol, params);
                if (matchVect.empty())
                {
                    msg_handler->msg(ACTStatus::Warning,
                                     gmx::formatString("Match found for %s '%s', but no matching atom pairs.",
                                                       abe[i].name.c_str(),
                                                       abe[i].smarts.c_str()));
                    continue;
                }
                std::vector<int> mapAtoms(exper->NAtom(), NOTSET);
                // Loop over all matches, there may be more than one, e.g.
                // a compound with two carboxylic groups.
                for(const auto &mv : matchVect)
                {
                    if (mv.size() != static_cast<size_t>(abe[i].atomtypes.size()))
                    {
                        msg_handler->msg(ACTStatus::Warning,
                                         gmx::formatString("Match found for %s '%s', but only %zu matching atom pair(s) out of %zu.",
                                                           abe[i].name.c_str(),
                                                           abe[i].smarts.c_str(),
                                                           mv.size(),
                                                           abe[i].atomtypes.size()));
                    }
                    else
                    {
                        for(const auto &mv2 : mv)
                        {
                            auto [ ai, aj ] = mv2;
                            if (mapAtoms[aj] != NOTSET)
                            {
                                msg_handler->msg(ACTStatus::Error,
                                                 "Inconsistency in output from Smarts matching");
                            }
                            mapAtoms[aj] = ai;
                        }
                    }
                }
                // Update atom types in the Experiment
                auto ca = exper->calcAtom();
                for(size_t j = 0; j < ca->size(); j++)
                {
                    if (mapAtoms[j] != NOTSET)
                    {
                        const auto &atype = abe[i].atomtypes[mapAtoms[j]];
                        bool isH = (atype.atomnumber == 1);
                        bool targetExists = pd->hasParticleType(atype.name);

                        if (!(oneH && isH && !targetExists) && !atomAssigned[j])
                        {
                            msg_handler->msg(ACTStatus::Verbose,
                                             gmx::formatString("Resetting type of %s %zu to %s",
                                                               (*ca)[j].getObtype().c_str(), j,
                                                               atype.name.c_str()));
                            (*ca)[j].setObtype(atype.name);
                            atomAssigned[j] = true;
                        }
                    }
                }
                // Now fix the bonds
                for(size_t bi = 0; bi < bonds->size(); bi++)
                {
                    auto &b = (*bonds)[bi];
                    if (bondAssigned[bi])
                    {
                        continue;
                    }
                    auto ai = mapAtoms[b.aI()];
                    auto aj = mapAtoms[b.aJ()];
                    if (ai != NOTSET and aj != NOTSET)
                    {
                        for(const auto &ab : abe[i].bonds)
                        {
                            if ((ab.ai == ai && ab.aj == aj) ||
                                (ab.ai == aj && ab.aj == ai))
                            {
                                b.setBondOrder(0, ab.order);
                                bondAssigned[bi] = true;
                                break;
                            }
                        }
                    }
                }
                // After we find our first match, and do everything that is needed,
                // we return to the calling routine.
            }
            else
            {
                msg_handler->msg(ACTStatus::Warning,
                                 gmx::formatString("Will ignore match in the AtomBondtype DB because the atom types or bonds are not supported by the force field."));
            }
        }
    }
}

/*! \brief Turn a molecule of RDKit into a MolProp
 * \param[in]    msg_handler For debugging and info
 * \param[in]    pd          Alexandria force field
 * \param[in]    abdb        The atom and bond type database
 * \param[in]    mol2        The molecule, with hydrogen atoms and a conformer
 * \param[in]    conf        Conformation the molecule is in
 * \param[in]    jobtype     Calculation type for reading QM output
 * \param[in]    oneH        Remap all hydrogen atom types to "h"
 * \param[out]   mps         The MolProp is added here if there was no error
 */
static void addMolProp(MsgHandler                           *msg_handler,
                       const ForceField                     *pd,
                       const std::vector<AtomBondtypeEntry> &abdb,
                       RDKit::RWMol                         *mol2,
                       const char                           *conf,
                       JobType                               jobtype,
                       bool                                  oneH,
                       std::vector<MolProp>                 *mps)
{
    MolProp      mp;
    const std::string  ref("Spoel2026a");
    //! \todo Check whether this is correct
    const std::string  RDKit_Unit("Angstrom");
    Experiment   exper(ref, conf);
    exper.setJobtype(jobtype);
    unsigned int atomid = 0;
    auto         conformer = mol2->getConformer();
    auto         bonds     = mol2->bonds();
    for(const auto &atom : mol2->atoms())
    {
        //standard assignment is now the lower case element
        std::string atype = atom->getSymbol();
        std::transform(atype.begin(), atype.end(), atype.begin(), ::tolower);
        CalcAtom ca(atom->getSymbol(), atype, atomid);
        const auto& atomPos = conformer.getAtomPos(atomid);
        ca.setCoords(convertToGromacs(atomPos.x, RDKit_Unit),
                     convertToGromacs(atomPos.y, RDKit_Unit),
                     convertToGromacs(atomPos.z, RDKit_Unit));
        exper.AddAtom(std::move(ca));
        atomid += 1;
    }
    for(const auto &bond : bonds)
    {
        double order = bondTypeValue(msg_handler, bond->getBondType());
        if (msg_handler->ok())
        {
            const Bond b(bond->getBeginAtomIdx(),
                         bond->getEndAtomIdx(),
                         order);
            mp.AddBond(std::move(b));
        }
    }
    // Now we have done the "default" atom types and bonds.
    // The actual atomtypes are assigned in the atom_bond.xml file, as well as special cases.
    lookUpSpecial(msg_handler, pd, abdb, mol2, &exper, mp.bonds(), oneH);
    if (msg_handler->ok())
    {
        const AlexandriaMols amols;
        mp.AddExperiment(std::move(exper));
        mp.generateFragments(msg_handler, pd);
        addInchiToFragments(msg_handler, amols, mol2, mp.fragmentPtr());
        mps->push_back(std::move(mp));
    }
}

/*! \brief Whether the bonds of a molecule from a PDB file lack their orders
 * CONECT records give the bonds, and a double bond by listing it twice.
 * Programs that list each bond once, as ACT does, leave all bonds
 * single, and RDKit then gives the atoms that have fewer bonds than their
 * valence implicit hydrogens, which makes pyridine piperidine and the
 * oxygen of acetone a hydroxyl. A file with hydrogens has them all, so
 * an implicit hydrogen means that bond orders are missing.
 * \param[in] mol The molecule as read, sanitized
 * \return true if the file has hydrogens, all bonds are single and an
 *         atom got implicit hydrogens
 */
static bool lacksBondOrders(const RDKit::RWMol &mol)
{
    bool hasHydrogen = false;
    bool implicitH   = false;
    for (const auto atom : mol.atoms())
    {
        hasHydrogen = hasHydrogen || atom->getAtomicNum() == 1;
        implicitH   = implicitH || atom->getNumImplicitHs() > 0;
    }
    for (const auto bond : mol.bonds())
    {
        if (bond->getBondType() != RDKit::Bond::SINGLE)
        {
            return false;
        }
    }
    return hasHydrogen && implicitH;
}

/*! \brief The charge of an atom without bonds, where RDKit gives a wrong one
 * RDKit gives an atom the formal charge that fills its octet. That is
 * right for a halide, but for an atom without bonds it is minus six for
 * helium, minus seven for an alkali metal and minus six for an alkaline
 * earth metal. The charges then do not add up to the total charge, and
 * RDKit finds no bond orders for the whole file.
 * \param[in]  atomicNumber The element
 * \param[out] charge       Zero for helium, one for the alkali metals and
 *                          two for the alkaline earth metals
 * \return whether it is one of these elements
 */
static bool loneAtomCharge(int  atomicNumber,
                           int *charge)
{
    switch (atomicNumber)
    {
    case 2:
        *charge = 0;
        return true;
    case 3:
    case 11:
    case 19:
    case 37:
    case 55:
    case 87:
        *charge = 1;
        return true;
    case 4:
    case 12:
    case 20:
    case 38:
    case 56:
    case 88:
        *charge = 2;
        return true;
    default:
        return false;
    }
}

/*! \brief Determine the bond orders of a molecule that may have helium atoms or metal ions
 * A helium atom, alkali metal or alkaline earth metal without bonds gets
 * the charge of loneAtomCharge, and the other atoms the remainder of the
 * total charge. These atoms are neon atoms, which have their octet, while
 * RDKit determines the bond orders.
 * \param[in] mol                   The molecule with its bonds
 * \param[in] charge                The total charge
 * \param[in] allowChargedFragments See RDKit
 * \param[in] embedChiral           See RDKit
 * \throws what RDKit throws if it finds no bond orders
 */
static void bondOrdersWithLoneAtoms(RDKit::RWMol &mol,
                                    int           charge,
                                    bool          allowChargedFragments = true,
                                    bool          embedChiral           = true)
{
    const int                                        neon      = 10;
    // The atoms, their elements and their charges
    std::vector<std::tuple<RDKit::Atom *, int, int>> lone;
    int                                              ionCharge = 0;
    for (auto atom : mol.atoms())
    {
        int q = 0;
        if (atom->getDegree() == 0 && loneAtomCharge(atom->getAtomicNum(), &q))
        {
            lone.emplace_back(atom, atom->getAtomicNum(), q);
            ionCharge += q;
            atom->setAtomicNum(neon);
            atom->setFormalCharge(0);
        }
    }
    const auto restore = [&lone]()
    {
        for (auto &[atom, element, q] : lone)
        {
            atom->setAtomicNum(element);
            atom->setFormalCharge(q);
            atom->setNoImplicit(true);
            atom->setNumRadicalElectrons(0);
            atom->updatePropertyCache(false);
        }
    };
    try
    {
        determineBondOrders(mol, charge - ionCharge, allowChargedFragments, embedChiral);
    }
    catch (const ValueErrorException &ve)
    {
        restore();
        if (ionCharge == 0)
        {
            throw;
        }
        throw ValueErrorException(gmx::formatString("%s. The metal atoms without bonds are ions with a total charge of %d, which leaves %d for the other atoms at the total charge of %d. Please check the total charge",
                                                    ve.what(), ionCharge, charge - ionCharge, charge));
    }
    catch (...)
    {
        restore();
        throw;
    }
    restore();
}

/*! \brief Determine the bonds of a molecule and their orders from the coordinates
 * As determineBonds of RDKit, but alkali and alkaline earth metals are
 * ions: RDKit finds bonds from the distances between the atoms, also from
 * a metal ion to the atoms next to it, and then no bond orders. Those bonds
 * are removed, as in a file with bonds, where sodium chloride has none.
 * See bondOrdersWithLoneAtoms for the charges.
 * \param[in] mol    The molecule without bonds
 * \param[in] charge The total charge
 * \throws what RDKit throws if it finds no bond orders
 */
static void bondsWithIons(RDKit::RWMol &mol,
                          int           charge)
{
    if (mol.getNumAtoms() == 1)
    {
        // RDKit does nothing for a single atom. It has the total charge.
        auto atom = mol.getAtomWithIdx(0);
        if (atom->getFormalCharge() != charge)
        {
            atom->setFormalCharge(charge);
            atom->setNoImplicit(true);
            atom->updatePropertyCache(false);
        }
        return;
    }
    determineConnectivity(mol, false, charge);
    std::vector<std::pair<unsigned int, unsigned int>> ionic;
    for (const auto bond : mol.bonds())
    {
        int q = 0;
        for (const auto atom : { bond->getBeginAtom(), bond->getEndAtom() })
        {
            if (atom->getAtomicNum() != 2 && loneAtomCharge(atom->getAtomicNum(), &q))
            {
                ionic.emplace_back(bond->getBeginAtomIdx(), bond->getEndAtomIdx());
                break;
            }
        }
    }
    for (const auto &[ai, aj] : ionic)
    {
        mol.removeBond(ai, aj);
    }
    if (!ionic.empty())
    {
        mol.updatePropertyCache(false);
    }
    bondOrdersWithLoneAtoms(mol, charge);
}

std::vector<int> wholeBondOrders(const std::vector<int>                 &atomicNumbers,
                                 const std::vector<gmx::RVec>           &coordinates,
                                 const std::vector<std::pair<int, int>> &bonds,
                                 const std::vector<double>              &orders,
                                 int                                     charge)
{
    std::vector<int> whole;
    bool             fractional = false;
    for (const double order : orders)
    {
        fractional = fractional || std::round(order) != order;
        whole.push_back(static_cast<int>(std::lround(order)));
    }
    if (!fractional)
    {
        return whole;
    }
    whole.clear();
    if (bonds.size() != orders.size() || coordinates.size() != atomicNumbers.size())
    {
        return whole;
    }
    RDKit::RWMol mol;
    auto        *conf = new RDKit::Conformer(atomicNumbers.size());
    for (size_t i = 0; i < atomicNumbers.size(); i++)
    {
        auto *atom = new RDKit::Atom(atomicNumbers[i]);
        // The hydrogens are all there
        atom->setNoImplicit(true);
        mol.addAtom(atom, true, true);
        // In Angstrom, as RDKit has them
        conf->setAtomPos(i, RDGeom::Point3D(10*coordinates[i][XX], 10*coordinates[i][YY],
                                            10*coordinates[i][ZZ]));
    }
    mol.addConformer(conf, true);
    for (const auto &bond : bonds)
    {
        mol.addBond(bond.first, bond.second, RDKit::Bond::SINGLE);
    }
    try
    {
        bondOrdersWithLoneAtoms(mol, charge, true, false);
    }
    catch (const std::exception &)
    {
        return whole;
    }
    for (size_t b = 0; b < bonds.size(); b++)
    {
        const auto *bond = mol.getBondBetweenAtoms(bonds[b].first, bonds[b].second);
        int         order = 0;
        switch (bond ? bond->getBondType() : RDKit::Bond::UNSPECIFIED)
        {
        case RDKit::Bond::SINGLE:
            order = 1;
            break;
        case RDKit::Bond::DOUBLE:
            order = 2;
            break;
        case RDKit::Bond::TRIPLE:
            order = 3;
            break;
        default:
            break;
        }
        // The same structure as ACT has, written with whole bonds
        if (order == 0 || std::abs(order - orders[b]) >= 1)
        {
            whole.clear();
            return whole;
        }
        whole.push_back(order);
    }
    return whole;
}

/*! \brief Read an sdf, pdb or xyz file using RDKit and add the molecule to a vector
 * For xyz files, and pdb files without bonds, the bonds are determined
 * by RDKit. Atom types are assigned from the atom and bond type database.
 * \param[in]    msg_handler For debugging, info and errors
 * \param[in]    pd          Alexandria force field
 * \param[in]    filenm      The file to read
 * \param[inout] mps         The molecule read is added here
 * \param[in]    conf        Conformation the molecule is in
 * \param[in]    jobtype     Calculation type for reading QM output
 * \param[in]    userqtot    Whether the user explicitly set the total charge
 * \param[in]    qtot        Total charge, used for determining bonds if userqtot or non-zero
 * \param[in]    oneH        Remap all hydrogen atom types to "h"
 * \param[in]    abdb        The atom and bond type database
 */
static void importFile(MsgHandler                           *msg_handler,
                       const ForceField                     *pd,
                       const std::string                    &filenm,
                       std::vector<MolProp>                 *mps,
                       const char                           *conf,
                       JobType                               jobtype,
                       bool                                  userqtot,
                       double                               *qtot,
                       bool                                  oneH,
                       const std::vector<AtomBondtypeEntry> &abdb)
{
    if (msg_handler->debug())
    {
        msg_handler->writeDebug(gmx::formatString("Will import file %s using the RDKit library", filenm.c_str()));
    }
    // Try to read the file
    try
    {
        RDKit::RWMol *mol2 = nullptr;
        const std::string ext = filenm.substr(filenm.size()-3, 3);
        if (ext == "sdf")
        {
            mol2 = RDKit::MolFileToMol( filenm, true, false, true );
        }
        else if (ext == "pdb")
        {
	        // filename, sanitize, removeHs, flavor, proximityBonding
            mol2 = RDKit::PDBFileToMol( filenm, true, false, true, false );
            // PDB files may include CONECT records. If present, assign bond orders
            // from the connectivity; otherwise infer connectivity and bond orders.
            mol2->updatePropertyCache();
            // The total charge for the bond orders
            const auto totalCharge = [&]()
            {
                if (userqtot || *qtot != 0)
                {
                    return static_cast<int>(*qtot);
                }
                return RDKit::MolOps::getFormalCharge(*mol2);
            };
            if (mol2->getNumBonds() == 0)
            {
                if (msg_handler->debug())
                {
                    msg_handler->writeDebug("PDB has no bonds; inferring connectivity and bond orders.");
                }
                bondsWithIons(*mol2, totalCharge());
            }
            else if (lacksBondOrders(*mol2))
            {
                if (msg_handler->debug())
                {
                    msg_handler->writeDebug(gmx::formatString("PDB has %u bonds without their orders; inferring the bond orders.",
                                                              mol2->getNumBonds()));
                }
                // The file has all hydrogens: none are added
                for (auto atom : mol2->atoms())
                {
                    atom->setNoImplicit(true);
                    atom->setNumExplicitHs(0);
                }
                mol2->updatePropertyCache(false);
                bondOrdersWithLoneAtoms(*mol2, totalCharge());
            }
            else
            {
                if (msg_handler->debug())
                {
                    msg_handler->writeDebug(gmx::formatString("PDB has %u bonds; Using these bonds going forward.",
                                                                mol2->getNumBonds()));
                }
            }
        }
        else if (ext == "xyz")
        {
            mol2 = RDKit::v1::XYZFileToMol( filenm );
            // Molecules from XYZ files need post-processing
            mol2->updatePropertyCache();
            int iqtot = 0;
            if (userqtot || *qtot != 0)
            {
                iqtot = int(*qtot);
            }
            else
            {
                iqtot = RDKit::MolOps::getFormalCharge(*mol2);
            }
            bondsWithIons(*mol2, iqtot);
        }
        if (mol2)
        {
            addMolProp(msg_handler, pd, abdb, mol2, conf, jobtype, oneH, mps);
            delete mol2;
        }
        else
        {
            msg_handler->msg(ACTStatus::Error,
                             gmx::formatString("Could not read molecule(s) from %s", filenm.c_str()));
        }
    }
    catch(ValueErrorException &ve)
    {
        msg_handler->msg(ACTStatus::Error,
                         gmx::formatString("Exception raised by RDKit: %s", ve.what() ) );
    }
}

/*! \brief The atom and bond type database, read when it is first needed
 * \param[in] msg_handler For debugging and info
 * \return the database
 */
static const std::vector<AtomBondtypeEntry> &atomBondtypeDB(MsgHandler *msg_handler)
{
    static std::vector<AtomBondtypeEntry> abe;
    if (abe.empty())
    {
        // Left empty on purpose.
        const std::string              dbname;
        readAtomBondtypeDB(msg_handler, dbname, &abe);
        if (msg_handler->debug())
        {
            writeAtomBondtypeDB(msg_handler, "atom_bond.xml", abe);
        }
    }
    return abe;
}

void importFile(MsgHandler             *msg_handler,
                const ForceField       *pd,
                const std::string      &filenm,
                std::vector<MolProp>   *mps,
                const char             *conf,
                JobType                 jobtype,
                bool                    userqtot,
                double                 *qtot,
                bool                    oneH)
{
    importFile(msg_handler, pd, filenm, mps, conf, jobtype, userqtot, qtot, oneH,
               atomBondtypeDB(msg_handler));
}

/*! \brief Keeps the handler of the program for the interrupt signal (Ctrl-C)
 *
 * RDKit installs a handler of its own while it makes or optimizes a
 * structure, to be able to stop, and puts back what it found. It keeps
 * what it found in one place for all its handlers, so when one of its
 * functions calls another, its own handler stays behind. The interrupt
 * then no longer reaches the program, or Python when ACT is used from
 * there. An object of this class puts back what was there when it was made.
 */
class InterruptHandlerKeeper
{
public:
    InterruptHandlerKeeper() { valid_ = (sigaction(SIGINT, nullptr, &before_) == 0); }
    ~InterruptHandlerKeeper()
    {
        if (valid_)
        {
            sigaction(SIGINT, &before_, nullptr);
        }
    }
    InterruptHandlerKeeper(const InterruptHandlerKeeper &)            = delete;
    InterruptHandlerKeeper &operator=(const InterruptHandlerKeeper &) = delete;

private:
    //! What was done with the signal when this object was made
    struct sigaction before_;
    //! Whether that could be found out
    bool             valid_ = false;
};

void importSmiles(MsgHandler           *msg_handler,
                  const ForceField     *pd,
                  const std::string    &smiles,
                  std::vector<MolProp> *mps,
                  bool                  oneH)
{
    const InterruptHandlerKeeper keeper;
    // Without the spaces around it
    const auto first = smiles.find_first_not_of(" \t\n\r");
    if (first == std::string::npos)
    {
        msg_handler->msg(ACTStatus::Error, "The SMILES string is empty");
        return;
    }
    const std::string smi = smiles.substr(first, smiles.find_last_not_of(" \t\n\r") - first + 1);
    if (smi.size() > maxSmilesLength)
    {
        msg_handler->msg(ACTStatus::Error,
                         gmx::formatString("The SMILES string has %zu characters, the maximum is %zu",
                                           smi.size(), maxSmilesLength));
        return;
    }
    if (msg_handler->debug())
    {
        msg_handler->writeDebug(gmx::formatString("Will make a molecule from SMILES '%s' using the RDKit library",
                                                  smi.c_str()));
    }
    try
    {
        // A null pointer for a string that cannot be parsed, an exception
        // for one that is not chemistry, e.g. a carbon with five bonds
        const std::unique_ptr<RDKit::RWMol> mol(RDKit::SmilesToMol(smi));
        if (!mol || mol->getNumAtoms() == 0)
        {
            msg_handler->msg(ACTStatus::Error,
                             gmx::formatString("Cannot interpret the SMILES string '%s'", smi.c_str()));
            return;
        }
        RDKit::MolOps::addHs(*mol);
        // Three-dimensional coordinates, the same every time
        auto params = RDKit::DGeomHelpers::ETKDGv3;
        params.randomSeed = 20261119;
        int  confId = RDKit::DGeomHelpers::EmbedMolecule(*mol, params);
        if (confId < 0)
        {
            // Starting from random coordinates works for more molecules
            params.useRandomCoords = true;
            confId = RDKit::DGeomHelpers::EmbedMolecule(*mol, params);
        }
        if (confId < 0)
        {
            msg_handler->msg(ACTStatus::Error,
                             gmx::formatString("Cannot make coordinates for the SMILES string '%s'", smi.c_str()));
            return;
        }
        // A rough optimization, which a minimization with the ACT force
        // field should follow. A molecule with one atom has nothing to
        // optimize. The optimization is done on a copy, since the force
        // fields of RDKit change the bonds of the molecule to their own
        // idea of what is aromatic, which is not that of the atom types.
        if (mol->getNumAtoms() > 1)
        {
            const int                      maxIters = 500;
            RDKit::RWMol                   work(*mol);
            RDKit::MMFF::MMFFMolProperties mmff(work);
            bool                           optimized = false;
            if (mmff.isValid())
            {
                RDKit::MMFF::MMFFOptimizeMolecule(work, maxIters);
                optimized = true;
            }
            else
            {
                // The check above may have changed the copy
                work = RDKit::RWMol(*mol);
                if (RDKit::UFF::getAtomTypes(work).second)
                {
                    RDKit::UFF::UFFOptimizeMolecule(work, maxIters);
                    optimized = true;
                }
            }
            if (optimized)
            {
                const auto &optimizedConformer = work.getConformer();
                auto       &conformer          = mol->getConformer();
                for (unsigned int i = 0; i < mol->getNumAtoms(); i++)
                {
                    conformer.setAtomPos(i, optimizedConformer.getAtomPos(i));
                }
            }
        }
        addMolProp(msg_handler, pd, atomBondtypeDB(msg_handler), mol.get(),
                   "minimum", JobType::OPT, oneH, mps);
    }
    catch (const std::exception &ex)
    {
        msg_handler->msg(ACTStatus::Error,
                         gmx::formatString("RDKit cannot make a molecule from the SMILES string '%s': %s",
                                           smi.c_str(), ex.what()));
    }
}

