"""
Tests of the OpenMM interface in act_openmm.py. They are skipped if OpenMM
cannot be imported or the alexandria program cannot be found, either in
the PATH or in the environment variable ACT_ALEXANDRIA.

Boxes of SPC/E water are simulated with OpenMM force fields generated by
alexandria gentop, with the Lennard-Jones potential, which OpenMM computes
with its native NonbondedForce, or with a buffered 14-7 potential, which
act_openmm.py computes with a CustomNonbondedForce. See
https://github.com/AlexandriaChemistry/ACT/issues/1344 for the long range
correction.
"""

import os, re, shutil, subprocess, sys, tempfile, unittest

try:
    import openmm
    import openmm.app
    import openmm.unit
    haveOpenMM = True
except ImportError:
    haveOpenMM = False

testDir    = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(testDir))
alexandria = os.environ.get("ACT_ALEXANDRIA", shutil.which("alexandria"))

# Simulation parameters, NONBONDED is replaced by the settings of a test
cutoff      = 0.6
datTemplate = """
usePlatform                      = Reference
usePrecision                     = double
minimizationSteps                = 0
equilibrationSteps               = 0
steps                            = 0
dt                               = 0.001*picoseconds
saveEnergy                       = 0
savePdb                          = 0
saveDcd                          = 0
temperature_c                    = 300.0*kelvin
temperature_s                    = 1.0*kelvin
friction_c                       = 5.0/picosecond
friction_s                       = 20.0/picosecond
collisionFrequency               = 10.0
commremovalFrequency             = 25
useAndersenThermostat            = False
useMonteCarloBarostat            = False
useMonteCarloAnisotropicBarostat = False
nonbondedCutoff                  = %g*nanometers
dielectricConstant               = 1.0
ewaldErrorTolerance              = 1e-5
useSwitchingFunction             = False
drudeMass                        = 0.1
maxDrudeDistance                 = 0.0
NONBONDED
""" % cutoff

# Lennard-Jones parameters of the SPC/E oxygen, the hydrogens have none
sigmaO   = 0.3165558
epsilonO = 0.65017032
sigmaH   = 0.225
# Buffered 14-7 parameters, those of Halgren for gamma and delta
gamma147 = 0.12
delta147 = 0.07

def waterBox(fileName:str, n:int=4, spacing:float=0.31):
    """ Write a box of n^3 water molecules on a grid, about 1 g/cm3 """
    geometry = [ ( "O",  0.0,     0.0,    0.0 ),
                 ( "H1", 0.1,     0.0,    0.0 ),
                 ( "H2", -0.0333, 0.0943, 0.0 ) ]
    box = 10*n*spacing
    with open(fileName, "w") as pdb:
        pdb.write("CRYST1%9.3f%9.3f%9.3f  90.00  90.00  90.00 P 1           1\n" % ( box, box, box ))
        atom = 1
        res  = 1
        for i in range(n):
            for j in range(n):
                for k in range(n):
                    for name, x, y, z in geometry:
                        pdb.write("ATOM  %5d %-4s HOH A%4d    %8.3f%8.3f%8.3f  1.00  0.00           %s\n" %
                                  ( atom, name, res, 10*(i*spacing + x), 10*(j*spacing + y),
                                    10*(k*spacing + z), name[0] ))
                        atom += 1
                    res += 1
        pdb.write("END\n")

def referenceTail(potential:str, pdbFile:str)->float:
    """
    The correction for the van der Waals potential of a water box computed
    with OpenMM itself, as the difference of the energies with and without it.
    potential is lj12_6, computed with the NonbondedForce of OpenMM, or
    lj14_7, computed with a CustomNonbondedForce.
    """
    pdb    = openmm.app.PDBFile(pdbFile)
    energy = {}
    for correction in [ True, False ]:
        system = openmm.System()
        system.setDefaultPeriodicBoxVectors(*pdb.topology.getPeriodicBoxVectors())
        if potential == "lj12_6":
            force = openmm.NonbondedForce()
            force.setNonbondedMethod(openmm.NonbondedForce.CutoffPeriodic)
            force.setUseDispersionCorrection(correction)
        else:
            # Arithmetic and geometric means as in the force field
            force = openmm.CustomNonbondedForce(
                "epsilon*((1+delta)/(rho+delta))^7*((1+gamma)/(rho^7+gamma)-2);"
                "rho=r/sigma; sigma=0.5*(sigma1+sigma2); epsilon=sqrt(epsilon1*epsilon2);"
                "gamma=0.5*(gamma1+gamma2); delta=0.5*(delta1+delta2)")
            for name in [ "sigma", "epsilon", "gamma", "delta" ]:
                force.addPerParticleParameter(name)
            force.setNonbondedMethod(openmm.CustomNonbondedForce.CutoffPeriodic)
            force.setUseLongRangeCorrection(correction)
        force.setCutoffDistance(cutoff)
        for atom in pdb.topology.atoms():
            oxygen = atom.element.symbol == "O"
            system.addParticle(16.0 if oxygen else 1.0)
            sigma, epsilon = ( sigmaO, epsilonO ) if oxygen else ( sigmaH, 0 )
            if potential == "lj12_6":
                force.addParticle(0, sigma, epsilon)
            else:
                force.addParticle([ sigma, epsilon, gamma147, delta147 ])
        system.addForce(force)
        context = openmm.Context(system, openmm.VerletIntegrator(0.001),
                                 openmm.Platform.getPlatformByName("Reference"))
        context.setPositions(pdb.positions)
        state = context.getState(getEnergy=True)
        energy[correction] = state.getPotentialEnergy().value_in_unit(openmm.unit.kilojoule_per_mole)
    return energy[True] - energy[False]

@unittest.skipUnless(haveOpenMM and alexandria, "OpenMM or alexandria not available")
class LongRangeCorrectionTest(unittest.TestCase):
    """ The long range correction of the van der Waals potential """

    @classmethod
    def setUpClass(cls):
        cls.workDir = tempfile.mkdtemp()
        spce = os.path.join(testDir, "..", "..", "properties", "tests", "SPCE.xml")
        with open(spce) as inf:
            ff = inf.read()
        # Only the oxygens have Lennard-Jones, such that the arithmetic
        # combination rule for sigma, which the native OpenMM force needs,
        # is the same as the geometric one.
        lj = ff.replace('<combinationrule parameter="sigma" rule="Geometric"/>',
                        '<combinationrule parameter="sigma" rule="Arithmetic"/>')
        # The same water with a buffered 14-7 potential
        def param(ptype, value, unit=""):
            return ('      <parameter type="%s" unit="%s" value="%.10g" uncertainty="0" minimum="0" maximum="10" ntrain="0" mutability="Fixed" nonnegative="yes"/>\n' %
                    ( ptype, unit, value ))
        def paramlist(ident, sigma, epsilon):
            return ('    <parameterlist identifier="%s">\n' % ident + param("delta", delta147) +
                    param("epsilon", epsilon, "kJ/mol") + param("gamma", gamma147) +
                    param("sigma", sigma, "nm") + '    </parameterlist>\n')
        vdw147 = ('<interaction type="VANDERWAALS" function="LJ14_7" canswap="true">\n'
                  '    <option key="nexcl" value="2"/>\n'
                  '    <combinationrule parameter="delta" rule="Arithmetic"/>\n'
                  '    <combinationrule parameter="epsilon" rule="Geometric"/>\n'
                  '    <combinationrule parameter="gamma" rule="Arithmetic"/>\n'
                  '    <combinationrule parameter="sigma" rule="Arithmetic"/>\n' +
                  paramlist("ho", sigmaH, 0) + paramlist("o3", sigmaO, epsilonO) + '  </interaction>')
        b147 = re.sub(r'<interaction type="VANDERWAALS".*?</interaction>', vdw147, ff, flags=re.S)
        water = os.path.join(cls.workDir, "water.pdb")
        waterBox(water, n=1)
        cls.xmlFile = {}
        for name, text in [ ( "lj12_6", lj ), ( "lj14_7", b147 ) ]:
            ffFile = os.path.join(cls.workDir, name + ".xml")
            with open(ffFile, "w") as outf:
                outf.write(text)
            cls.xmlFile[name] = os.path.join(cls.workDir, name + "_openmm.xml")
            result = subprocess.run([ alexandria, "gentop", "-ff", ffFile, "-f", water,
                                      "-openmm", cls.xmlFile[name] ],
                                    cwd=cls.workDir, capture_output=True, text=True)
            if result.returncode != 0 or not os.path.exists(cls.xmlFile[name]):
                raise RuntimeError("alexandria gentop failed:\n" + result.stdout + result.stderr)
        cls.pdbFile = os.path.join(cls.workDir, "box.pdb")
        waterBox(cls.pdbFile)

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.workDir, ignore_errors=True)

    def simulate(self, ff:str, label:str, nonbonded:str):
        """
        Set up a simulation of the water box with force field ff, lj12_6 or
        lj14_7, and the settings nonbonded for the nonbonded forces. Returns
        a dictionary from the name of each force to its type, energy and
        corrections, and the text of the log file.
        """
        from act_openmm import ActOpenMMSim
        datFile = os.path.join(self.workDir, label + ".dat")
        txtFile = os.path.join(self.workDir, label + ".txt")
        with open(datFile, "w") as outf:
            outf.write(datTemplate.replace("NONBONDED", nonbonded))
        cwd = os.getcwd()
        os.chdir(self.workDir)
        try:
            sim = ActOpenMMSim(pdbfile=self.pdbFile, datfile=datFile, xmlfile=self.xmlFile[ff],
                               txtfile=txtFile, verbose=False)
            sim.setup()
            # The forces cannot be used after the simulation is gone
            forces = {}
            for force in sim.system.getForces():
                group  = force.getForceGroup()
                state  = sim.simulation.context.getState(getEnergy=True, groups=(1 << group))
                energy = state.getPotentialEnergy().value_in_unit(openmm.unit.kilojoule_per_mole)
                info   = { "type": type(force).__name__, "energy": energy }
                if isinstance(force, openmm.CustomNonbondedForce):
                    info["longRange"] = force.getUseLongRangeCorrection()
                elif isinstance(force, openmm.NonbondedForce):
                    info["dispersion"] = force.getUseDispersionCorrection()
                forces[force.getName()] = info
            sim.txt.close()
        finally:
            os.chdir(cwd)
        with open(txtFile) as inf:
            log = inf.read()
        return forces, log

    @staticmethod
    def settings(method:str, disp:str)->str:
        return "nonbondedMethod = %s\nuseDispersionCorrection = %s\nuseOpenMMForce = False" % ( method, disp )

    def customForces(self, forces):
        """ Return the van der Waals CustomNonbondedForce and the other ones """
        custom = { name: info for name, info in forces.items() if info["type"] == "CustomNonbondedForce" }
        vdw    = [ info for name, info in custom.items() if name.startswith("VanderWaals") ]
        others = { name: info for name, info in custom.items() if not name.startswith("VanderWaals") }
        self.assertEqual(1, len(vdw), "Forces: %s" % ", ".join(forces.keys()))
        return vdw[0], others

    def test_custom_periodic(self):
        """
        Only the custom van der Waals force gets the long range correction if
        requested, and it is the same as for the potential written for OpenMM
        """
        expected = referenceTail("lj14_7", self.pdbFile)
        self.assertLess(expected, 0)
        for method in [ "CutoffPeriodic", "PME" ]:
            energy = {}
            for disp in [ "True", "False" ]:
                forces, _ = self.simulate("lj14_7", "%s_%s" % ( method, disp ), self.settings(method, disp))
                vdw, others = self.customForces(forces)
                self.assertEqual(disp == "True", vdw["longRange"], method)
                for name, info in others.items():
                    self.assertFalse(info["longRange"], "%s %s" % ( method, name ))
                energy[disp] = vdw["energy"]
            self.assertAlmostEqual(expected, energy["True"] - energy["False"],
                                   delta=1e-6*abs(expected), msg=method)

    def test_custom_ljpme(self):
        """ With LJPME the dispersion beyond the cut-off is in reciprocal space """
        forces, _ = self.simulate("lj14_7", "LJPME", self.settings("LJPME", "True"))
        vdw, _ = self.customForces(forces)
        self.assertFalse(vdw["longRange"])

    def test_native(self):
        """
        Lennard-Jones is computed with the native NonbondedForce, which gets
        the dispersion correction if requested
        """
        expected = referenceTail("lj12_6", self.pdbFile)
        self.assertLess(expected, 0)
        energy   = {}
        for disp in [ "True", "False" ]:
            forces, _ = self.simulate("lj12_6", "native_%s" % disp, self.settings("CutoffPeriodic", disp))
            native = [ info for info in forces.values() if info["type"] == "NonbondedForce" ]
            self.assertEqual(1, len(native))
            self.assertEqual(disp == "True", native[0]["dispersion"])
            energy[disp] = native[0]["energy"]
        self.assertAlmostEqual(expected, energy["True"] - energy["False"], delta=1e-6*abs(expected))

    def test_long_range_correction_ignored(self):
        """ useLongRangeCorrection is not used, but gives a warning """
        forces, log = self.simulate("lj14_7", "ignored",
                                    "nonbondedMethod = PME\nuseLongRangeCorrection = True\nuseOpenMMForce = False")
        vdw, _ = self.customForces(forces)
        self.assertFalse(vdw["longRange"])
        self.assertTrue("WARNING: useLongRangeCorrection" in log, "No warning in the log file")

if __name__ == "__main__":
    unittest.main()
